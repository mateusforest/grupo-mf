let offset = 0
export const COMPANY_AGENTS = DEPARTMENTS.flatMap((department) => {
  const first = offset + 1
  const agents = Array.from({ length: department.count }, (_, i) => {
    const number = first + i
    const scope = 'Grupo MF'
    return {
      id: `MF-${String(number).padStart(3, '0')}`,
      number,
      departmentId: department.id,
      role: department.roles[i % department.roles.length],
      scope,
      mission: department.mission,
      managerId:
        number === 1
          ? null
          : i === 0
            ? 'MF-001'
            : `MF-${String(first).padStart(3, '0')}`,
      color: department.color,
    }
  })
  offset += department.count
  return agents
})

export type CompanyAgent = (typeof COMPANY_AGENTS)[number]
